def prepare_still(src: str, dst: str, width: int | None = None) -> str:
    """Fit a full-body photo into width x HEIGHT: scale to HEIGHT, then edge-pad or centre-crop the width."""
    width = width or WIDTH
    import numpy as np
    from PIL import Image

    im = Image.open(src).convert("RGB")
    new_w = round(im.width * HEIGHT / im.height)
    arr = np.asarray(im.resize((new_w, HEIGHT), Image.LANCZOS))
    pad = width - new_w
    if pad > 0:
        arr = np.pad(arr, ((0, 0), (pad // 2, pad - pad // 2), (0, 0)), mode="edge")
    elif pad < 0:
        arr = arr[:, -pad // 2 : -pad // 2 + width]
    Image.fromarray(arr).save(dst)
    return dst


IMAGE_EXTS = (".png", ".jpg", ".jpeg", ".webp")


@dataclass(frozen=True)
class Subject:
    """One person to try on: ``inputs/subjects/<name>/front.*`` + ``back.*`` (+ optional ``prompt.txt``)."""

    name: str
    front: str  # absolute path
    back: str
    prompt: str


def _find_image(folder: str, stem: str) -> str | None:
    import os

    for ext in IMAGE_EXTS:
        path = os.path.join(folder, stem + ext)
        if os.path.exists(path):
            return path
    return None


def discover_subjects(inputs_root: str = "/inputs") -> list[Subject]:
    """Every folder under ``<inputs_root>/subjects`` with a front and back photo becomes a subject.

    The prompt defaults to GENERIC_PROMPT (the photos carry person and outfit); put a ``prompt.txt`` in the
    subject folder to override it.
    """
    import os

    root = os.path.join(inputs_root, "subjects")
    subjects = []
    for name in sorted(os.listdir(root)) if os.path.isdir(root) else []:
        folder = os.path.join(root, name)
        front, back = _find_image(folder, "front"), _find_image(folder, "back")
        if not (os.path.isdir(folder) and front and back):
            continue
        prompt_file = os.path.join(folder, "prompt.txt")
        prompt = open(prompt_file, encoding="utf-8").read().strip() if os.path.exists(prompt_file) else GENERIC_PROMPT
        subjects.append(Subject(name=name, front=front, back=back, prompt=prompt))
    if not subjects:
        raise SystemExit(
            f"No subjects found in {root}. Add inputs/subjects/<name>/front.png and back.png (see inputs/README.md)."
        )
    return subjects


def with_gpu_retry(fn, precisions, label, runs_per_subject, require_gpu, attempts: int = 6):
    """Call a Modal suite function, retrying when Modal assigns a different GPU variant."""
    for i in range(attempts):
        try:
            return fn.remote(precisions, label, runs_per_subject, require_gpu)
        except Exception as e:  # noqa: BLE001  WrongGpu arrives wrapped by Modal
            if "WrongGpu" not in type(e).__name__ and "WrongGpu" not in repr(e):
                raise
            print(f"[retry {i + 1}/{attempts}] got {e}; need '{require_gpu}', retrying")
    raise RuntimeError(f"could not get a GPU matching {require_gpu!r}")


